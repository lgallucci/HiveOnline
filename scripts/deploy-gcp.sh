#!/usr/bin/env bash
# Builds the HiveServer image with Cloud Build and runs it on a small Compute Engine VM
# with a static public IP and a firewall rule for the game port.
# Usage: PROJECT=my-gcp-project ./scripts/deploy-gcp.sh   (re-run to deploy a new version)
set -euo pipefail

PROJECT="gen-lang-client-0379014683" #${PROJECT:?Set PROJECT to your GCP project id}"
# PFX created once with: dotnet run --project HiveServer -- --generate-cert hive-server.pfx
CERT_FILE="./hive-server.pfx" #"${CERT_FILE:?Set CERT_FILE to the PFX generated by HiveServer --generate-cert}"
CERT_B64=$(base64 -w0 "$CERT_FILE")
# The always-free e2-micro is only free in us-central1, us-east1 and us-west1.
REGION="${REGION:-us-central1}"
ZONE="${ZONE:-us-central1-a}"
PORT="${PORT:-7777}"
VM="${VM:-hive-server}"
REPO="${REPO:-hive}"
IMAGE="$REGION-docker.pkg.dev/$PROJECT/$REPO/hiveserver:latest"

cd "$(dirname "$0")/.."
gcloud config set project "$PROJECT" >/dev/null

gcloud services enable compute.googleapis.com cloudbuild.googleapis.com artifactregistry.googleapis.com

gcloud artifacts repositories describe "$REPO" --location "$REGION" >/dev/null 2>&1 ||
  gcloud artifacts repositories create "$REPO" --repository-format=docker --location "$REGION"

gcloud builds submit --tag "$IMAGE" .

gcloud compute firewall-rules describe allow-hive >/dev/null 2>&1 ||
  gcloud compute firewall-rules create allow-hive --allow "tcp:$PORT" --target-tags hive-server

gcloud compute addresses describe "$VM-ip" --region "$REGION" >/dev/null 2>&1 ||
  gcloud compute addresses create "$VM-ip" --region "$REGION"
IP=$(gcloud compute addresses describe "$VM-ip" --region "$REGION" --format='value(address)')

# Container-Optimized OS already ships Docker; the startup script (re-run on every boot) pulls
# the latest image and runs it. Settings are passed as instance metadata.
STARTUP=$(mktemp)
trap 'rm -f "$STARTUP"' EXIT
cat > "$STARTUP" <<'SCRIPT'
#!/bin/bash
md() { curl -s -H 'Metadata-Flavor: Google' "http://metadata.google.internal/computeMetadata/v1/instance/attributes/$1"; }
export HOME=/home/chronos
IMAGE=$(md hive-image)
docker-credential-gcr configure-docker --registries="${IMAGE%%/*}"
docker pull "$IMAGE"
docker rm -f hive-server 2>/dev/null
PORT=$(md hive-port)
docker run -d --name hive-server --restart always -p "$PORT:$PORT" \
  -e HIVE_PORT="$PORT" -e HIVE_TLS=1 -e HIVE_CERT_BASE64="$(md hive-cert-b64)" "$IMAGE"
SCRIPT
CERT_META=$(mktemp)
trap 'rm -f "$STARTUP" "$CERT_META"' EXIT
printf '%s' "$CERT_B64" > "$CERT_META"
METADATA="hive-image=$IMAGE,hive-port=$PORT"

if gcloud compute instances describe "$VM" --zone "$ZONE" >/dev/null 2>&1; then
  gcloud compute instances add-metadata "$VM" --zone "$ZONE" \
    --metadata "$METADATA" --metadata-from-file "startup-script=$STARTUP,hive-cert-b64=$CERT_META"
  # Rebooting re-runs the startup script, which pulls the new image.
  gcloud compute instances reset "$VM" --zone "$ZONE"
else
  gcloud compute instances create "$VM" --zone "$ZONE" \
    --machine-type e2-micro --boot-disk-size 30GB --boot-disk-type pd-standard --address "$IP" --tags hive-server \
    --image-family cos-stable --image-project cos-cloud \
    --metadata "$METADATA" --metadata-from-file "startup-script=$STARTUP,hive-cert-b64=$CERT_META" \
    --scopes cloud-platform
fi

echo "Server running at $IP:$PORT"
echo "Clients connect to $IP:$PORT using the public key pin printed by --generate-cert."
